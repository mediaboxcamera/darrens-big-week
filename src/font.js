export const FONT_CHARS = Object.keys(G).join('');
export const CHAR_W = 6, CHAR_H = 8; // 5x7 glyph + 1px gap

/** Draw the glyph atlas onto a canvas texture and register the RetroFont. */
export function installFont(scene, key = 'pix') {
  const chars = FONT_CHARS;
  const perRow = 16, rows = Math.ceil(chars.length / perRow);
  const canvas = scene.textures.createCanvas(key + '_img', perRow * CHAR_W, rows * CHAR_H);
  const ctx = canvas.getContext();
  ctx.fillStyle = '#ffffff';
  for (let i = 0; i < chars.length; i++) {
    const g = G[chars[i]];
    const ox = (i % perRow) * CHAR_W, oy = Math.floor(i / perRow) * CHAR_H;
    for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) if (g[y][x] === '1') ctx.fillRect(ox + x, oy + y, 1, 1);
  }
  canvas.refresh();
  const config = { image: key + '_img', width: CHAR_W, height: CHAR_H, chars, charsPerRow: perRow, 'spacing.x': 0, 'spacing.y': 0 };
  scene.cache.bitmapFont.add(key, Phaser.GameObjects.RetroFont.Parse(scene, config));
}
