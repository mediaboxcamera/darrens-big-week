#!/usr/bin/env node
// Flat build for hosts that only accept a single folder of files with no
// sub-directories (e.g. drag-and-drop uploads). Bundles the ES modules into one
// classic script and puts every asset at the root. Output: /dist-flat
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIST = path.join(ROOT, 'dist');
const OUT = path.join(ROOT, 'dist-flat');
if (!fs.existsSync(path.join(DIST, 'index.html'))) { console.error('run `npm run build` first'); process.exit(1); }
fs.rmSync(OUT, { recursive: true, force: true }); fs.mkdirSync(OUT);

// --- bundle src/ modules in dependency order ------------------------------
const SRC = path.join(ROOT, 'src');
const files = [];
(function walk(d) { for (const f of fs.readdirSync(d)) { const p = path.join(d, f); fs.statSync(p).isDirectory() ? walk(p) : p.endsWith('.js') && files.push(p); } })(SRC);
const deps = new Map();
for (const f of files) {
  const src = fs.readFileSync(f, 'utf8');
  const list = [];
  for (const m of src.matchAll(/^import\s.*?from\s+['"](\..*?)['"];?\s*$/gm)) list.push(path.resolve(path.dirname(f), m[1]));
  deps.set(f, list);
}
const order = [], seen = new Set();
const visit = (f) => { if (seen.has(f)) return; seen.add(f); for (const d of deps.get(f) || []) visit(d); order.push(f); };
for (const f of files) visit(f);
let bundle = '/* Darren\'s Big Week - flat bundle (generated by tools/build_flat.js) */\n';
for (const f of order) {
  let s = fs.readFileSync(f, 'utf8');
  s = s.replace(/^import\s.*?from\s+['"].*?['"];?\s*$/gm, '');
  s = s.replace(/^export\s+(const|let|class|function|async function)\b/gm, '$1');
  s = s.replace(/`sprites\/\$\{s\}\.png`/g, '`${s}.png`'); // assets live at the root
  bundle += `\n// ---- ${path.relative(ROOT, f)} ----\n${s}\n`;
}
fs.writeFileSync(path.join(OUT, 'game.js'), bundle);

// --- copy assets flat ----------------------------------------------------------
const cp = (s, d) => fs.copyFileSync(s, path.join(OUT, d));
for (const f of fs.readdirSync(path.join(DIST, 'sprites'))) cp(path.join(DIST, 'sprites', f), f);
for (const f of fs.readdirSync(path.join(DIST, 'icons'))) cp(path.join(DIST, 'icons', f), f);
cp(path.join(DIST, 'vendor/phaser.min.js'), 'phaser.min.js');
cp(path.join(DIST, 'style.css'), 'style.css');
fs.writeFileSync(path.join(OUT, 'manifest.webmanifest'), fs.readFileSync(path.join(DIST, 'manifest.webmanifest'), 'utf8').replace(/icons\//g, ''));
let html = fs.readFileSync(path.join(DIST, 'index.html'), 'utf8')
  .replace('vendor/phaser.min.js', 'phaser.min.js').replace('<script type="module" src="src/main.js"></script>', '<script src="game.js"></script>').replace(/icons\//g, '');
fs.writeFileSync(path.join(OUT, 'index.html'), html);
console.log(`built dist-flat/ (${fs.readdirSync(OUT).length} files)`);
